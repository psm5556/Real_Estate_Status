// fullName에서 최단 표시명 추출 (마지막 > 이후)
export function getShortName(fullName: string): string {
  const parts = fullName.split(">");
  return parts[parts.length - 1].trim();
}

// 트리 구조 빌드
export function buildRegionTree(): RegionNode[] {
  const roots: RegionNode[] = [];
  const nodeMap = new Map<string, RegionNode>();

  // 깊이순으로 정렬하여 처리
  const entries = Object.entries(REGION_CODES).sort((a, b) => {
    const depthA = a[0].split(">").length;
    const depthB = b[0].split(">").length;
    return depthA - depthB;
  });

  for (const [fullName, code] of entries) {
    const parts = fullName.split(">").map((p) => p.trim());
    const name = parts[parts.length - 1];
    const node: RegionNode = { code, name, fullName, children: [] };
    nodeMap.set(fullName, node);

    if (parts.length === 1) {
      roots.push(node);
    } else {
      const parentFullName = parts.slice(0, -1).join(">");
      const parent = nodeMap.get(parentFullName);
      if (parent) {
        parent.children.push(node);
      } else {
        roots.push(node);
      }
    }
  }

  return roots;
}
